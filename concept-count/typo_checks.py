"""Misspell one concept at a time and see when each framework notices.

    python3 -m pip install -r requirements.txt
    python3 typo_checks.py

Each case runs in a fresh temporary directory. The Django cases use a real
project generated by `startproject` and Django's own `manage.py check`.
"""
from __future__ import annotations

import os
import subprocess
import sys
import tempfile
from pathlib import Path

PY = sys.executable


def sh(args: list[str], cwd: Path, env: dict | None = None) -> str:
    out = subprocess.run(args, cwd=cwd, capture_output=True, text=True, env={**os.environ, **(env or {})})
    lines = [l.strip() for l in (out.stdout + out.stderr).splitlines() if l.strip()]
    errors = [l for l in lines if "Error" in l or "Warning" in l]
    return (errors[-1] if errors else lines[-1]).replace("INTERNALERROR> ", "")


def django_project(work: Path, old: str, new: str) -> Path:
    subprocess.run([PY, "-m", "django", "startproject", "mysite", str(work)], check=True)
    settings = work / "mysite" / "settings.py"
    text = settings.read_text()
    assert old in text
    settings.write_text(text.replace(old, new))
    return work


def django_middleware_path(work: Path) -> str:
    django_project(work, "'django.middleware.common.CommonMiddleware'", "'django.middleware.common.CommonMiddlewar'")
    check = sh([PY, "manage.py", "check"], work)
    load = sh([PY, "-c", "from django.core.wsgi import get_wsgi_application; get_wsgi_application()"], work,
              {"DJANGO_SETTINGS_MODULE": "mysite.settings"})
    return f"manage.py check: {check}\n    loading the app, as the server does: {load}"


def django_setting_name(work: Path) -> str:
    django_project(work, "TIME_ZONE = 'UTC'", "TIME_ZONES = 'Europe/Paris'")
    check = sh([PY, "manage.py", "check"], work)
    zone = sh([PY, "manage.py", "shell", "-c", "from django.conf import settings; print('TIME_ZONE =', settings.TIME_ZONE)"], work)
    return f"manage.py check: {check}\n    {zone}"


def pytest_case(work: Path, conftest: str, test: str) -> str:
    if conftest:
        (work / "conftest.py").write_text(conftest)
    (work / "test_a.py").write_text(test)
    out = subprocess.run([PY, "-m", "pytest", "-q", "-p", "no:cacheprovider"], cwd=work, capture_output=True, text=True)
    lines = [l.strip().replace("INTERNALERROR> ", "") for l in (out.stdout + out.stderr).splitlines() if l.strip()]
    found = [l.split(" in plugin")[0] for l in lines if l.startswith("pluggy") and "PluginValidationError" in l]
    found += [l[l.index("PytestUnknownMarkWarning"):].split(" - ")[0] for l in lines if "PytestUnknownMarkWarning" in l]
    return "; ".join(found + [lines[-1]])


def fastapi_param(work: Path) -> str:
    code = (
        "import warnings; warnings.simplefilter('ignore')\n"
        "from fastapi import FastAPI\nfrom fastapi.testclient import TestClient\n"
        "app = FastAPI()\n"
        "@app.get('/items/{item_id}')\n"
        "def read_item(itemid: int):\n    return {'item_id': itemid}\n"
        "print('app built;', end=' ')\n"
        "r = TestClient(app).get('/items/5')\n"
        "print('GET /items/5 ->', r.status_code, r.json()['detail'][0]['type'], r.json()['detail'][0]['loc'])\n"
    )
    return sh([PY, "-c", code], work)


CASES = [
    ("Django, a typo inside a middleware path", django_middleware_path),
    ("Django, a typo in a setting's name", django_setting_name),
    ("pytest, a typo in a hook's name",
     lambda w: pytest_case(w, "def pytest_colection_modifyitems(config, items):\n    pass\n", "def test_ok():\n    pass\n")),
    ("pytest, a typo in the hook prefix",
     lambda w: pytest_case(w, "def pytst_collection_modifyitems(config, items):\n    raise SystemExit('ran')\n", "def test_ok():\n    pass\n")),
    ("pytest, a typo in a marker's name",
     lambda w: pytest_case(w, "", "import pytest\n\n@pytest.mark.slwo\ndef test_ok():\n    pass\n")),
    ("FastAPI, a parameter name that doesn't match the path", fastapi_param),
]


def main() -> int:
    for label, run in CASES:
        with tempfile.TemporaryDirectory() as tmp:
            result = run(Path(tmp))
        print(f"{label}:\n    {result}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
